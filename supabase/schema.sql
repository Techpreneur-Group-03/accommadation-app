-- Mirrors src/data/sample-data.ts (camelCase in TS, snake_case in Postgres).
create table if not exists public.houses (
  id bigint generated by default as identity primary key,
  house_id bigint not null unique,
  house_name text not null,
  owner_name text not null,
  location text not null,
  number_of_room integer not null,
  people_per_room integer not null,
  price_per_room numeric(10, 2) not null,
  rate numeric(3, 2) not null,
  phone_number text not null,
  house_image text not null default '',
  created_at timestamptz not null default now()
);

